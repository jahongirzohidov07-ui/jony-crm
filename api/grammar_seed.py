def seed_grammar(db):
    """Bazaga yetishmayotgan savollarni qo'shadi (idempotent)."""
    import json
    import models
    have = {(t, p) for (t, p) in
            db.query(models.GrammarQuestion.topic,
                     models.GrammarQuestion.prompt).all()}
    made = 0
    for order, (topic, level, questions) in enumerate(SEED):
        for kind, prompt, options, answer, explain in questions:
            if (topic, prompt) in have:
                continue
            db.add(models.GrammarQuestion(
                topic=topic, level=level, topic_order=order,
                kind=kind, prompt=prompt,
                options=json.dumps(options, ensure_ascii=False),
                answer=answer, explain=explain))
            made += 1
    if made:
        db.commit()
    return made

