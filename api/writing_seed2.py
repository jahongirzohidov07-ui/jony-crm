def seed_writing2(db):
    """Idempotent: (skill, kind, payload) bo'yicha yo'qlari qo'shiladi.

    Alohida marker (writing_v2) — practice_v2 allaqachon qo'yilgan
    bazalarda eski seed qayta ishlamaydi va bu to'plam tushmay
    qolardi. Hech narsa o'chirilmaydi."""
    from common import _seed_done, _seed_mark
    if _seed_done(db, "writing_v2"):
        return None
    import json
    import models
    have = {(r.skill, r.kind, r.payload) for r in
            db.query(models.PracticeItem)
            .filter(models.PracticeItem.skill == "writing").all()}
    made = 0
    for lvl, instr, given, ans, alt, expl in W2:
        payload = json.dumps({"instruction": instr, "given": given},
                             ensure_ascii=False, sort_keys=True)
        if ("writing", "write_transform", payload) in have:
            continue
        db.add(models.PracticeItem(
            skill="writing", kind="write_transform", level=lvl,
            payload=payload, answer=ans,
            alt=json.dumps(alt, ensure_ascii=False),
            explain=expl, is_active=1))
        made += 1
    if made:
        db.commit()
    _seed_mark(db, "writing_v2")
    return made
