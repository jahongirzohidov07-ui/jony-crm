def seed_vocab(db) -> int:
    """Yetishmayotgan so'zlarni qo'shadi. Idempotent: qayta
    ishga tushsa dublikat yaratmaydi, mavjudini o'zgartirmaydi."""
    import models
    have = {(w.word or "").lower()
            for w in db.query(models.VocabWord).all()}
    added = 0
    for word, translation, level in SEED_WORDS:
        if word.lower() in have:
            continue
        db.add(models.VocabWord(
            word=word, translation=translation, level=level,
            is_active=1, created_by="JonyOS boshlang'ich"))
        added += 1
    if added:
        db.commit()
    return added
