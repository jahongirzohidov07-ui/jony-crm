def seed_grammar(db):
    """A1 savollarini yuklaydi, eski umumiy mavzularni o'chiradi."""
    import json
    import models

    new_topics = {t for _, _, t, _ in SEED_A1}

    # Eski (2026-08-10 dagi) mavzularni yashiramiz - urinishlar qoladi
    (db.query(models.GrammarQuestion)
     .filter(~models.GrammarQuestion.topic.in_(new_topics),
             models.GrammarQuestion.is_active == 1)
     .update({models.GrammarQuestion.is_active: 0},
             synchronize_session=False))

    have = {(t, p) for (t, p) in
            db.query(models.GrammarQuestion.topic,
                     models.GrammarQuestion.prompt).all()}
    made = 0
    for order, is_boss, topic, questions in SEED_A1:
        for kind, prompt, options, answer, explain in questions:
            if (topic, prompt) in have:
                continue
            db.add(models.GrammarQuestion(
                topic=topic, level="A1", topic_order=order,
                is_boss=1 if is_boss else 0,
                kind=kind, prompt=prompt,
                options=json.dumps(options, ensure_ascii=False),
                answer=answer, explain=explain))
            made += 1
    db.commit()
    return made

