def seed_grammar_levels(db):
    """A2/B1/B2 savollari + A1 qolgan cloze. Idempotent."""
    from common import _seed_done, _seed_mark
    if _seed_done(db, "grammar_l2_v1"):
        return None
    import json
    import models

    have = {(t, p) for (t, p) in
            db.query(models.GrammarQuestion.topic,
                     models.GrammarQuestion.prompt).all()}
    made = 0

    def _add_level(seed, level):
        nonlocal made
        for order, is_boss, topic, questions in seed:
            for kind, prompt, options, answer, explain in questions:
                if (topic, prompt) in have:
                    continue
                db.add(models.GrammarQuestion(
                    topic=topic, level=level, topic_order=order,
                    is_boss=1 if is_boss else 0,
                    kind=kind, prompt=prompt,
                    options=json.dumps(options, ensure_ascii=False),
                    answer=answer, explain=explain))
                have.add((topic, prompt))
                made += 1

    _add_level(SEED_A2, "A2")
    _add_level(SEED_B1, "B1")
    _add_level(SEED_B2, "B2")

    def _add_cloze(seed, level, order_of):
        nonlocal made
        for topic, prompt, opts, answers, explain in seed:
            if (topic, prompt) in have or topic not in order_of:
                continue
            o, b = order_of[topic]
            db.add(models.GrammarQuestion(
                topic=topic, level=level, topic_order=o,
                is_boss=1 if b else 0, kind="cloze", prompt=prompt,
                options=json.dumps(opts, ensure_ascii=False),
                answer=json.dumps(answers, ensure_ascii=False),
                explain=explain))
            have.add((topic, prompt))
            made += 1

    from grammar_seed import SEED_A1
    order_a1 = {t: (o, b) for o, b, t, _ in SEED_A1}
    order_a2 = {t: (o, b) for o, b, t, _ in SEED_A2}
    _add_cloze(SEED_CLOZE_A1_EXTRA, "A1", order_a1)
    _add_cloze(SEED_A2_CLOZE, "A2", order_a2)

    db.commit()
    _seed_mark(db, "grammar_l2_v1")
    return made
